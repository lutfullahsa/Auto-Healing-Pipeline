import base64
import json
import docker
import pandas as pd
import time
from typing import Any, Optional
from pydantic import BaseModel
from app.sandbox.code_validator import CodeSecurityValidator
from app.core.schema_analyzer import SchemaAnalyzer

class SandboxResult(BaseModel):
    passed: bool
    output: str
    execution_time_ms: int
    error_type: Optional[str] = None

class DockerSandboxRunner:
    def __init__(self, image_name: str = "autoheal-sandbox:latest", timeout_seconds: int = 15):
        self.image_name = image_name
        self.timeout_seconds = timeout_seconds
        self.validator = CodeSecurityValidator()
        self.analyzer = SchemaAnalyzer()

    def run_etl_test(self, python_code: str, sample_rows: list[dict[str, Any]], expected_schema: dict[str, str]) -> SandboxResult:
        # 1. Security Check
        is_safe, msg = self.validator.validate_ast(python_code)
        if not is_safe:
            return SandboxResult(passed=False, output=msg, execution_time_ms=0, error_type="Security Violation")

        start_time = time.time()
        client = docker.from_env()
        container = None
        payload = {
            "python_code": python_code,
            "sample_rows": sample_rows,
            "expected_schema": expected_schema
        }
        payload_b64 = base64.b64encode(
            json.dumps(payload).encode("utf-8")
        ).decode("ascii")

        runner_script = """
import base64
import contextlib
import io
import json
import os
import sys
import pandas as pd

result_prefix = "AUTOHEAL_RESULT:"
try:
    payload = json.loads(
        base64.b64decode(os.environ["PAYLOAD_B64"], validate=True).decode("utf-8")
    )
    namespace = {}
    with contextlib.redirect_stdout(io.StringIO()):
        exec(compile(payload["python_code"], "<transform>", "exec"), namespace)
        transform = namespace.get("transform")
        if not callable(transform):
            raise TypeError("Transform code must define a callable transform(df).")
        result_df = transform(pd.DataFrame(payload["sample_rows"]))
    if not isinstance(result_df, pd.DataFrame):
        raise TypeError("transform(df) must return a pandas DataFrame.")
    print(result_prefix + result_df.to_json(orient="records"))
except Exception as error:
    print(result_prefix + json.dumps({"error": str(error)}))
    sys.exit(1)
"""

        try:
            container = client.containers.run(
                self.image_name,
                command=["python", "-c", runner_script],
                environment={"PAYLOAD_B64": payload_b64},
                network_mode="none",
                mem_limit="256m",
                nano_cpus=500000000,
                detach=True
            )

            # 4. Timeout handling
            result = container.wait(timeout=self.timeout_seconds)
            exit_code = result.get("StatusCode")
            logs = container.logs().decode("utf-8", errors="replace")
            result_prefix = "AUTOHEAL_RESULT:"
            result_json = next(
                (
                    line[len(result_prefix):]
                    for line in reversed(logs.splitlines())
                    if line.startswith(result_prefix)
                ),
                None
            )
            execution_time_ms = int((time.time() - start_time) * 1000)

            if exit_code != 0:
                error_msg = logs.strip() or "Execution failed"
                if result_json:
                    error_msg = json.loads(result_json).get("error", error_msg)
                return SandboxResult(
                    passed=False,
                    output=error_msg,
                    execution_time_ms=execution_time_ms,
                    error_type="Runtime Error"
                )

            if result_json is None:
                return SandboxResult(
                    passed=False,
                    output="No output generated by sandbox process",
                    execution_time_ms=execution_time_ms,
                    error_type="Output Error"
                )

            result_df = pd.DataFrame(json.loads(result_json))
            diff = self.analyzer.analyze_dataframe(result_df, expected_schema)

            passed = (
                not diff["missing_columns"]
                and not diff["type_mismatches"]
            )
            return SandboxResult(
                passed=passed,
                output=str(diff) if not passed else "OK",
                execution_time_ms=execution_time_ms,
                error_type=None if passed else "Schema Mismatch"
            )

        except docker.errors.APIError as e:
            return SandboxResult(
                passed=False,
                output=str(e),
                execution_time_ms=int((time.time() - start_time) * 1000),
                error_type="System Error"
            )
        except Exception as e:
            # Handle Timeout or other errors
            if "timed out" in str(e).lower():
                return SandboxResult(
                    passed=False,
                    output="Execution timed out",
                    execution_time_ms=self.timeout_seconds * 1000,
                    error_type="Timeout Error"
                )
            return SandboxResult(
                passed=False,
                output=str(e),
                execution_time_ms=int((time.time() - start_time) * 1000),
                error_type="System Error"
            )

        finally:
            if container:
                try:
                    container.remove(force=True)
                except:
                    pass